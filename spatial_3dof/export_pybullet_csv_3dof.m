function export_pybullet_csv_3dof(traj, result, output_file)
%EXPORT_PYBULLET_CSV_3DOF Export one trajectory for PyBullet playback.

T = table(result.t, ...
    traj.q(:, 1), traj.q(:, 2), traj.q(:, 3), ...
    traj.dq(:, 1), traj.dq(:, 2), traj.dq(:, 3), ...
    traj.ddq(:, 1), traj.ddq(:, 2), traj.ddq(:, 3), ...
    result.q(:, 1), result.q(:, 2), result.q(:, 3), ...
    result.x_d, result.y_d, result.z_d, ...
    result.x, result.y, result.z, ...
    'VariableNames', {'t', 'q1_d', 'q2_d', 'q3_d', ...
    'dq1_d', 'dq2_d', 'dq3_d', 'ddq1_d', 'ddq2_d', 'ddq3_d', ...
    'q1', 'q2', 'q3', 'x_d', 'y_d', 'z_d', 'x', 'y', 'z'});

writetable(T, output_file);
end
